package main

import (
	"fmt"
	"sync"
)

var counter int

func main() {
	var wg sync.WaitGroup
	var mu sync.Mutex // защищает доступ к counter

	for i := 0; i < 100; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := 0; j < 1000; j++ {
				mu.Lock()
				counter++ // теперь только одна горутина здесь в каждый момент
				mu.Unlock()
			}
		}()
	}

	wg.Wait()
	fmt.Println("Counter:", counter) // стабильно 100000
}


/*

- Мьютекс — это замок на участок кода. Lock() пропускает внутрь только одну горутину; остальные, дойдя до Lock(), засыпают в очереди и ждут Unlock().
- Пока одна горутина делает все три шага load→add→store, никто другой физически не может войти. Три шага становятся логически неделимыми — переплетения нет.
- Дополнительно Unlock()/Lock() создают happens-before связь: запись одной горутины гарантированно видна следующей.
- Цена: если замок занят, горутина уходит в сон и потом просыпается — это обращение к планировщику/ядру. При миллионах захватов накладные расходы копятся.

*/