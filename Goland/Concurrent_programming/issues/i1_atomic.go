package main

import (
	"fmt"
	"sync"
	"sync/atomic"
)

var counter int64 // atomic работает с int32/int64

func main() {
	var wg sync.WaitGroup

	for i := 0; i < 100; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := 0; j < 1000; j++ {
				atomic.AddInt64(&counter, 1) // атомарный инкремент, без мьютекса
			}
		}()
	}

	wg.Wait()
	// читать общую переменную тоже атомарно
	fmt.Println("Counter:", atomic.LoadInt64(&counter)) // стабильно 100000
}

/*
- Здесь нет замка. AddInt64 компилируется в одну атомарную инструкцию процессора (на x86 — LOCK XADD). Процессор гарантирует, что load→add→store выполнятся как единое целое — другое ядро не может вклиниться в середину.
- Синхронизация происходит на уровне железа (кеш-когерентность CPU), а не через сон/пробуждение горутин. Никто не «засыпает».
- Ограничение: это работает только для одной простой операции над одним числом. Защитить составную логику (изменить два поля разом) атомиком нельзя — там нужен мьютекс.


Сравнение скорости

На 100 млн инкрементов (1000 горутин × 100000):

Версия		Замер_1	Замер_2	Замер_3
sync.Mutex	12.18 s	12.70 s	11.80 s
sync/atomic	1.58 s	1.34 s	1.57 s

Atomic примерно в 8 раз быстрее. Причина: 
- мьютекс при высокой конкуренции постоянно усыпляет и будит 
горутины (дорогие обращения к планировщику), 
а atomic решает всё одной инструкцией CPU без переключений контекста.

*/